; ============================================================================
;  JoyOS (胡闹OS) — PIT(8253/8254 定时器)
;
;  在这之前,系统里根本没有"时间":speaker.asm 的注释写着"音高是准的,时值是估的",
;  因为它只能靠忙等循环数数。PIT 通道 0 每 10 ms 敲一次 IRQ0,系统这才有心跳:
;     tick 计数器 → uptime / sleep → (以后)多任务的时间片轮转
;
;  硬件(三个通道共用 0x43 命令口):
;     通道 0 = 0x40,计数器输出接 IRQ0        ← 这个文件在用的
;     通道 1 = 0x41,给内存刷新用(别碰)
;     通道 2 = 0x42,驱动扬声器(speaker.asm 在用,和这里不冲突)
;  输入时钟固定 1193182 Hz(老 IBM PC 拿 14.31818 MHz ÷ 12 来的)。
;  divisor = 1193182 / 目标频率,这里给 11932 → 约 100 Hz(差 0.002%)。
;
;  IRQ0 怎么接上:PIC 的重映射在 keyboard.asm 的 kbd_init 里做(IRQ0 → 0x20),
;  但那儿只放行了 IRQ1(屏蔽字 0xFD)。这里装 0x20 号向量 + 把屏蔽字改成 0xFC,
;  所以 **pit_init 必须排在 kbd_init 之后** —— 不然 PIC 还没重映射,PIT 的中断
;  会打到 0x08 这个 BIOS 自己用的向量上(那是一片我们没碰过的空间)。
;
;  老实交代:32 位 tick 计数器在 100 Hz 下 497 天回绕一次,这里不管(玩具够用)。
; ============================================================================

PIT_CH0     equ 0x40                    ; 通道 0 数据口(连着 IRQ0)
PIT_DIV     equ 11932                   ; 1193182 / 11932 ≈ 100 Hz
TICK_HZ     equ 100                     ; 一秒几个 tick(shell 拿它换算秒)
IRQ0_VECTOR equ 0x20                    ; IRQ0 重映射后的向量号(= IRQ_BASE)
; 注意:PIT_HZ(1193182)和 PIT_CMD(0x43)在 speaker.asm 里定义,同一个镜像共用。

; ---------------------------------------------------------------------------
;  pit_init:给通道 0 编程 100 Hz + 装 IRQ0 入口 + 放开 PIC 屏蔽位
; ---------------------------------------------------------------------------
pit_init:
    pushad

    ; ---- 1) 编程通道 0:模式 3(方波),先送低字节再送高字节,二进制计数 ----
    ;      命令字节 0x36 = 00(通道0) 11(先低后高) 011(模式3) 0(二进制)
    mov al, 0x36
    out PIT_CMD, al
    mov ax, PIT_DIV
    out PIT_CH0, al                     ; 低字节
    mov al, ah
    out PIT_CH0, al                     ; 高字节

    ; ---- 2) 装 IRQ0 的入口(0x20 号向量)----
    mov eax, IRQ0_VECTOR
    mov ebx, irq0_stub
    call idt_install

    ; ---- 3) 放开 IRQ0:屏蔽字 bit0 清 0 ----
    ;      必须读-改-写:直接写 0xFE 会把 IRQ1(键盘)一起关掉
    in al, PIC1_DAT
    and al, 0xFE
    out PIC1_DAT, al

    mov dword [pit_ticks], 0
    popad
    ret

; ---------------------------------------------------------------------------
;  IRQ0 入口:栈格式和键盘那个保持一致(假错误码 + 向量号)
;  中断门(0x8E)进来时 CPU 已经关了中断,处理完 iret 会恢复 EFLAGS 里的 IF。
; ---------------------------------------------------------------------------
irq0_stub:
    push dword 0
    push dword IRQ0_VECTOR
    pushad
    call pit_irq

    ; ---- 抢占式多任务:要不要换人 ----
    ;  此刻 esp 指着 pushad 压出来的现场,把它交给调度器:它返回"下一个线程"
    ;  的 esp,我们一句 mov 换过去 —— 下面的 popad + iret 就回到另一个人身上了。
    ;  (换栈必须在这一层做:如果调度器自己换,它的 ret 会从别人的栈上弹地址)
    cmp dword [sched_on], 0
    je .no_sched
    mov [sched_save_esp], esp
    call sched_pick
    mov esp, eax
.no_sched:
    popad
    add esp, 8                          ; 丢掉"向量号 + 假错误码"
    iret

; ---------------------------------------------------------------------------
;  pit_irq:一次心跳。只干两件事:数一个 tick、告诉 PIC 处理完了。
;
;  顺序是刻意的:**先发 EOI,再回 irq0_stub 里调度** —— 不先告诉 PIC 处理完了,
;  新线程跑起来后 IRQ0 就再也不来了(定时器"死"了,屏幕上还看不出来)。
;  上下文切换本身在 irq0_stub 里(那儿才方便换栈),这里只管数数和 EOI。
; ---------------------------------------------------------------------------
pit_irq:
    push eax
    inc dword [pit_ticks]
    mov al, PIC_EOI
    out PIC1_CMD, al
    pop eax
    ret

; ---------------------------------------------------------------------------
;  pit_get_ticks:→ eax = 开机以来的 tick 数(100 Hz)
;  32 位读在 x86 上是原子的,不用关中断。
; ---------------------------------------------------------------------------
pit_get_ticks:
    mov eax, [pit_ticks]
    ret

; ---------------------------------------------------------------------------
;  pit_wait_ticks:ecx = 要等的 tick 数 —— 用 hlt 睡过去,不烧 CPU
;
;  为什么能 hlt:IRQ0 每 10 ms 必来一次,就算键盘一声不响,CPU 也会被叫醒。
;  比较用"差值是不是负"来判断,这样 tick 计数器回绕了也不会卡死
;  (前缀式的"目标值比较"在回绕那一刻会等成 2^32 个 tick)。
; ---------------------------------------------------------------------------
pit_wait_ticks:
    push eax
    push ecx
    push edx
    call pit_get_ticks
    add ecx, eax                        ; edx = 到点时的 tick 数
    mov edx, ecx
.wait:
    hlt
    call pit_get_ticks
    sub eax, edx
    js .wait                            ; 差值还是负的 → 还没到
    pop edx
    pop ecx
    pop eax
    ret

; ---------------------------------------------------------------------------
;  数据
; ---------------------------------------------------------------------------
pit_ticks   dd 0                        ; 开机以来的 tick 数(100 Hz)
