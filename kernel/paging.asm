; ============================================================================
;  JoyOS (胡闹OS) — 分页(页目录 + 页表)
;
;  ── 分页在干嘛 ──────────────────────────────────────────────────────────
;  开分页之前,线性地址就是物理地址。开了 CR0.PG 之后,CPU 把线性地址
;  按 两级页表 翻译成物理地址:
;
;      线性地址 = [ 页目录索引(10 位) | 页表索引(10 位) | 页内偏移(12 位) ]
;                    ↓ 查 CR3 指向的页目录(4 KiB,1024 项 × 4 字节)
;                    ↓ 查出页表基址,再查页表(4 KiB,1024 项)
;                    ↓ 查出**物理页**基址,加上偏移
;
;  每个表项 4 字节:高 20 位 = 物理页基址(所以页必须 4 KiB 对齐),
;  低 12 位是标志位。这里只用两个:
;      bit0 P   present   1 = 这页存在,0 = 不存在(访问就触发 14 号页错误)
;      bit1 R/W writable  1 = 可写,0 = 只读
;  所以 "物理页 | 0x3" = 存在且可写。
;
;  一个页表管 4 MiB(1024 项 × 4 KiB),一个页目录管 4 GiB。
;
;  ── 这个阶段干的事 ──────────────────────────────────────────────────────
;  1. 恒等映射(线性 = 物理)前 4 MiB —— 内核、VGA(0xB8000)、IDT、栈都在里面,
;     这样开分页的那一瞬间,正在跑的代码地址不变,不会当场飞掉
;  2. 另外把 0x00400000 映射到物理 0x00100000,表示"虚拟地址和物理地址可以不一样"
;  3. 开 CR0.PG
;  开之前必须先把要用的表都填好,开之后下一条指令就得在映射范围内 —— 顺序不能错。
;
;  页目录/页表放在物理 0x1000、0x2000、0x3000(空闲低内存)。
;  现在先硬编码这几个地址,等有内存管理器了再改成动态分配。
; ============================================================================

PD_ADDR     equ 0x1000                 ; 页目录(4 KiB)
PT_LOW      equ 0x2000                 ; 页表:管 0x000000-0x3FFFFF(前 4 MiB)
PT_DEMO     equ 0x3000                 ; 页表:管 0x400000-0x7FFFFF

DEMO_VADDR  equ 0x00400000             ; 演示用虚拟地址(1 MiB 处)
DEMO_PADDR  equ 0x00100000             ; 它映到的物理地址

PAGE_P      equ 1                      ; bit0 present
PAGE_RW     equ 2                      ; bit1 writable

; ---------------------------------------------------------------------------
;  paging_init:建表 → 开分页
; ---------------------------------------------------------------------------
paging_init:
    pushad

    ; ---- 1) 把 0x1000~0x3FFF 这 12 KiB 清零(页目录 + 两个页表)----
    mov edi, PD_ADDR
    mov ecx, (3 * 4096) / 4            ; 12 KiB ÷ 4 字节 = 3072 个双字
    xor eax, eax
    rep stosd

    ; ---- 2) 页目录:第 0 项 → PT_LOW,第 1 项 → PT_DEMO ----
    mov eax, PT_LOW
    or  eax, PAGE_P | PAGE_RW
    mov [PD_ADDR + 0 * 4], eax         ; 页目录[0] 管 0x00000000-0x003FFFFF
    mov eax, PT_DEMO
    or  eax, PAGE_P | PAGE_RW
    mov [PD_ADDR + 1 * 4], eax         ; 页目录[1] 管 0x00400000-0x007FFFFF

    ; ---- 3) PT_LOW:1024 个页,恒等映射(线性 = 物理)----
    mov edi, PT_LOW
    mov eax, PAGE_P | PAGE_RW          ; 从物理 0 开始
    mov ecx, 1024
.fill_low:
    mov [edi], eax
    add edi, 4
    add eax, 4096                      ; 下一页
    dec ecx
    jnz .fill_low

    ; ---- 4) PT_DEMO:第 0 项 → DEMO_VADDR 映到 DEMO_PADDR ----
    mov eax, DEMO_PADDR
    or  eax, PAGE_P | PAGE_RW
    mov [PT_DEMO + 0 * 4], eax

    ; ---- 5) CR3 ← 页目录物理地址,然后开 CR0.PG ----
    mov eax, PD_ADDR
    mov cr3, eax
    mov eax, cr0
    or  eax, 0x80000000                ; CR0.PG = 1
    mov cr0, eax

    popad
    ret
